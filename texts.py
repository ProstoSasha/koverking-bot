def deadline(start_dt: datetime, now: datetime) -> str:
    days = (start_dt.date() - now.date()).days
    if days <= 0:
        head = "⏳ Мастер-класс уже сегодня, поэтому на выбор эскиза остался всего час."
    elif days == 1:
        head = "⏳ Мастер-класс завтра, поэтому на выбор эскиза остаётся 2 часа."
    else:
        last = start_dt.date() - timedelta(days=2)
        head = f"⏳ Эскиз нужно выбрать за 2 дня до мастер-класса, то есть до {last:%d.%m} включительно."
    return head + DEADLINE_TAIL


